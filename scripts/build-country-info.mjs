#!/usr/bin/env node
// Builds constants/countryInfo.ts (Before you go, spec 2026-11-12) from scripts/data/country-info.txt (hard facts)
// and scripts/data/country-extras.txt (tipping, tap water, Airalo page). Edit the .txt files, then run:
//   node scripts/build-country-info.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const rows = (f) => readFileSync(join(root, 'scripts/data', f), 'utf8').split('\n').filter((l) => l.trim() && !l.startsWith('#')).map((l) => l.split('|'));
const extras = new Map(rows('country-extras.txt').map(([code, tipping, water, slug]) => [code, { tipping, water, slug }]));
const q = (s) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

const lines = rows('country-info.txt').sort((a, b) => a[0].localeCompare(b[0])).map(([code, name, plugs, volts, cur, curName, emergency, drive]) => {
  const x = extras.get(code) ?? {};
  const parts = [
    `name: ${q(name)}`, `plugs: [${plugs.split(',').map(q).join(', ')}]`, `voltage: ${Number(volts)}`,
    `currency: { code: ${q(cur)}, name: ${q(curName)} }`, `emergency: ${q(emergency)}`, `drive: ${drive === 'L' ? "'left'" : "'right'"}`,
    ...(x.tipping ? [`tipping: ${q(x.tipping)}`] : []), ...(x.water ? [`tapWater: ${q(x.water)}`] : []), ...(x.slug ? [`airaloSlug: ${q(x.slug)}`] : []),
  ];
  return `  ${code}: { ${parts.join(', ')} },`;
});
for (const code of extras.keys()) if (!lines.some((l) => l.startsWith(`  ${code}:`))) throw new Error(`extras for unknown country ${code}`);

writeFileSync(join(root, 'constants/countryInfo.ts'), `/**
 * Before you go (spec 2026-11-12): per-country travel basics, built in so it works offline and costs nothing.
 * Hard facts (plugs, voltage, currency, emergency, drive) for every country; tipping and tap water only where
 * confident (every catalog country), never guessed. airaloSlug = Airalo's country page path (checked to exist).
 * GENERATED by scripts/build-country-info.mjs from scripts/data/*.txt — edit those, not this file.
 */
export interface CountryInfo {
  name: string;
  /** IEC plug letters, e.g. ['C', 'E']. */
  plugs: string[];
  voltage: number;
  currency: { code: string; name: string };
  /** The emergency number(s) travellers should dial; the first number is the one a tap calls. */
  emergency: string;
  drive: 'left' | 'right';
  tipping?: string;
  tapWater?: 'safe' | 'bottled';
  airaloSlug?: string;
}

export const COUNTRY_INFO: Record<string, CountryInfo> = {
${lines.join('\n')}
};
`);
console.log(`wrote ${lines.length} countries`);
