#!/usr/bin/env node
/**
 * Builds the airport → time zone table used to show boarding-pass times in the airport's local time
 * (functions/src/airportZones.ts for the passes, data/airportZones.ts for the app).
 *
 *   curl -sSL -o /tmp/airports.json https://raw.githubusercontent.com/mwgg/Airports/master/airports.json
 *   node scripts/build-airport-zones.mjs /tmp/airports.json
 *
 * Source: mwgg/Airports (MIT, © 2014 mwgg). Grouped by zone so the table stays ~36 KB: { zone: "AMSRTM…" }.
 */
import { readFileSync, writeFileSync } from 'node:fs';

const src = process.argv[2];
if (!src) { console.error('Usage: node scripts/build-airport-zones.mjs <airports.json>'); process.exit(1); }
const byZone = {};
let n = 0;
for (const a of Object.values(JSON.parse(readFileSync(src, 'utf8')))) {
  if (!a.iata || !/^[A-Z]{3}$/.test(a.iata) || !a.tz) continue;
  try { new Intl.DateTimeFormat('en-US', { timeZone: a.tz }); } catch { continue; }
  (byZone[a.tz] ??= []).push(a.iata); n++;
}
const sorted = Object.fromEntries(Object.keys(byZone).sort().map((z) => [z, byZone[z].sort().join('')]));
const body = `/** Generated by scripts/build-airport-zones.mjs from mwgg/Airports (MIT, © 2014 mwgg) — ${n} airports. Do not edit by hand. */\nexport const AIRPORT_ZONES: Record<string, string> = ${JSON.stringify(sorted)};\n`;
for (const out of ['functions/src/airportZones.ts', 'data/airportZones.ts']) writeFileSync(out, body);
console.log(`${n} airports in ${Object.keys(sorted).length} zones, ${body.length} bytes each`);

// Day-of assistant (spec 2026-11-01): each airport's location and country, for the leave-for-the-airport drive
// and the domestic/international buffer. Server only.
const info = {};
for (const a of Object.values(JSON.parse(readFileSync(src, 'utf8')))) {
  if (!a.iata || !/^[A-Z]{3}$/.test(a.iata) || typeof a.lat !== 'number' || typeof a.lon !== 'number' || !a.country) continue;
  info[a.iata] = [Math.round(a.lat * 1000) / 1000, Math.round(a.lon * 1000) / 1000, String(a.country).toUpperCase()];
}
const infoBody = `/** Generated by scripts/build-airport-zones.mjs from mwgg/Airports (MIT, © 2014 mwgg) — ${Object.keys(info).length} airports. Do not edit by hand. */
export const AIRPORTS: Record<string, [number, number, string]> = ${JSON.stringify(info)};

/** An airport's location and country by IATA code, or null. */
export function airportInfo(iata: string): { lat: number; lng: number; country: string } | null {
  const a = AIRPORTS[(iata ?? '').trim().toUpperCase()];
  return a ? { lat: a[0], lng: a[1], country: a[2] } : null;
}
`;
writeFileSync('functions/src/airportInfo.ts', infoBody);
console.log(`airport info: ${Object.keys(info).length} airports, ${infoBody.length} bytes`);
